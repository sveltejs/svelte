// @vitest-environment jsdom
import { afterEach, assert, describe, it } from 'vitest';
import { compile, compileModule } from 'svelte/compiler';
import { flushSync, mount, unmount } from 'svelte';
import { listen } from 'svelte/internal/devtools';
import { FILENAME, HMR } from '../../src/constants.js';
import { hmr } from '../../src/internal/client/dev/hmr.js';
import { proxy } from '../../src/internal/client/proxy.js';

const source = `<script>let count = $state(0); $effect(() => {});</script><button onclick={() => count++}>{count}</button>`;

describe('experimental.devtools compiler option', () => {
	it('prepends one import per runtime to dev client components, in order', () => {
		const { js } = compile(source, {
			dev: true,
			filename: 'App.svelte',
			experimental: { devtools: ['plugin-a/runtime', '/abs/plugin-b.js'] }
		});

		assert.ok(
			js.code.startsWith(`import 'plugin-a/runtime';\nimport '/abs/plugin-b.js';\n`),
			js.code
		);
	});

	it('prepends imports to dev client modules', () => {
		const { js } = compileModule(`export const count = $state({ value: 0 });`, {
			dev: true,
			filename: 'state.svelte.js',
			experimental: { devtools: ['plugin-a/runtime'] }
		});

		// after the `/* state.svelte.js generated by Svelte */` header
		const [, ...lines] = js.code.split('\n');
		assert.equal(lines[0], `import 'plugin-a/runtime';`);
		assert.equal(lines[1], `import * as $ from 'svelte/internal/client';`);
		assert.include(js.code, `'state.svelte.js:1:13'`);
	});

	it('is ignored outside of dev, on the server, and when empty', () => {
		const options = { experimental: { devtools: ['plugin-a/runtime'] } };

		assert.notInclude(compile(source, options).js.code, 'plugin-a');
		assert.notInclude(
			compile(source, { ...options, dev: true, generate: 'server' }).js.code,
			'plugin-a'
		);
		assert.notInclude(compileModule('export {}', options).js.code, 'plugin-a');

		const empty = compile(source, { dev: true, experimental: { devtools: [] } }).js.code;
		const missing = compile(source, { dev: true }).js.code;
		assert.equal(empty, missing);
	});

	it('validates the option', () => {
		assert.throws(
			// @ts-expect-error
			() => compile(source, { experimental: { devtools: 'plugin-a/runtime' } }),
			/experimental\.devtools should be an array of module specifiers/
		);
	});

	it('passes locations to tags and effects in dev', () => {
		const { js } = compile(source, { dev: true, filename: 'App.svelte' });

		assert.include(js.code, `$.tag($.state(0), 'count', 'App.svelte:1:12')`);
		assert.include(js.code, `'App.svelte:1:31'`);
	});
});

describe('listen', () => {
	const unlisteners: Array<() => void> = [];

	afterEach(() => {
		for (const unlisten of unlisteners.splice(0)) unlisten();
	});

	it('requires a name', () => {
		// @ts-expect-error
		assert.throws(() => listen({}), /must have a non-empty `name`/);
	});

	it('replaces plugins with the same name, and ignores a stale unlisten', () => {
		const log: string[] = [];

		const first = listen({ name: 'a', componentCreated: () => log.push('first') });
		unlisteners.push(listen({ name: 'a', componentCreated: () => log.push('second') }));

		// the first subscription was replaced, so its unlisten must not remove the second
		first();

		const target = document.createElement('div');
		const app = mount((() => {}) as any, { target });
		unmount(app);

		assert.deepEqual(log, ['second']);
	});

	it('rejects writes through proxy traps without changing state', () => {
		const object = proxy<Record<string, any>>({ a: 1 });
		const array = proxy([1, 2, 3]);
		const messages: string[] = [];

		const writes = [
			() => delete object.a,
			() => (object.b = 2),
			() =>
				Object.defineProperty(object, 'c', {
					value: 3,
					configurable: true,
					enumerable: true,
					writable: true
				}),
			() => (array.length = 1)
		];

		unlisteners.push(
			listen({
				name: 'writer',
				componentCreated() {
					for (const write of writes) {
						try {
							write();
							messages.push('no error');
						} catch (error) {
							messages.push((error as Error).message);
						}
					}
				}
			})
		);

		const target = document.createElement('div');
		const app = mount((() => {}) as any, { target });
		unmount(app);

		assert.deepEqual(
			{
				messages,
				a: object.a,
				keys: Object.keys(object),
				b: 'b' in object,
				c: 'c' in object,
				array: [...array]
			},
			{
				messages: writes.map(() => 'Devtools plugins must not write state inside their callbacks'),
				a: 1,
				keys: ['a'],
				b: false,
				c: false,
				array: [1, 2, 3]
			}
		);
	});

	it('brackets HMR updates', () => {
		const log: string[] = [];

		unlisteners.push(
			listen({
				name: 'hmr',
				hmrUpdateStart: (filename) => log.push(`start ${filename}`),
				hmrUpdateEnd: (filename) => log.push(`end ${filename}`),
				effectDestroyed: () => {
					if (log.length > 0 && log.at(-1) !== 'destroyed') log.push('destroyed');
				}
			})
		);

		const a: any = () => {};
		a[FILENAME] = 'A.svelte';

		const b: any = () => {};
		b[FILENAME] = 'A.svelte';

		const wrapper: any = hmr(a);
		const target = document.createElement('div');
		const app = mount(wrapper, { target });

		// no bracket for the initial render
		assert.deepEqual(log, []);

		wrapper[HMR].update(hmr(b));
		flushSync();

		assert.deepEqual(log, ['start A.svelte', 'destroyed', 'end A.svelte']);

		unmount(app);
	});
});
