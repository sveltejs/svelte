/** @import { Message } from '@sveltejs/message-box' */

// @ts-check
import process from 'node:process';
import fs from 'node:fs';
import { parse, render } from '@sveltejs/message-box';

const DIR = '../../documentation/docs/98-reference/.generated';

const watch = process.argv.includes('-w');

function run() {
	/** @type {Record<string, Record<string, Message>>} */
	const messages = {};
	const seen = new Set();

	fs.rmSync(DIR, { force: true, recursive: true });
	fs.mkdirSync(DIR);

	for (const category of fs.readdirSync('messages')) {
		if (category.startsWith('.')) continue;

		messages[category] = {};

		for (const file of fs.readdirSync(`messages/${category}`)) {
			if (!file.endsWith('.md')) continue;

			const markdown = fs
				.readFileSync(`messages/${category}/${file}`, 'utf-8')
				.replace(/\r\n/g, '\n');

			for (const message of parse(markdown)) {
				if (seen.has(message.code)) {
					throw new Error(`Duplicate message code ${category}/${message.code}`);
				}

				seen.add(message.code);
				messages[category][message.code] = message;
			}

			const sorted = Array.from(
				markdown.matchAll(/## ([\w]+)\n\n([^]+?)(?=$|\n\n## )/g),
			).map((m) => m[0]).sort();

			fs.writeFileSync(
				`messages/${category}/${file}`,
				sorted.map((x) => x.trim()).join('\n\n') + '\n'
			);
		}

		fs.writeFileSync(
			`${DIR}/${category}.md`,
			'<!-- This file is generated by scripts/process-messages/index.js. Do not edit! -->\n\n' +
				Object.entries(messages[category])
					.map(([code, { variants, details }]) => {
						const chunks = [`### ${code}`, ...variants.map(({ text }) => '```\n' + text + '\n```')];

						if (details) {
							chunks.push(details);
						}

						return chunks.join('\n\n');
					})
					.sort()
					.join('\n\n') +
				'\n'
		);
	}

	/**
	 * @param {string} name
	 * @param {string} dest
	 */
	function transform(name, dest) {
		const source = fs
			.readFileSync(new URL(`./templates/${name}.js`, import.meta.url), 'utf-8')
			.replace(/\r\n/g, '\n');
		const marker = '/**\n * DESCRIPTION';
		const index = source.lastIndexOf(marker);

		if (index === -1) throw new Error(`missing message template in ${name}.js`);

		const category = messages[name];
		const codes = `[\n${Object.keys(category)
			.map((code) => `\t'${code}'`)
			.join(',\n')}\n]`;
		const preamble = source.slice(0, index).trimEnd().replace('CODES', codes);
		const template = source.slice(index).trim();
		const output = Object.values(category)
			.map((message) => render(message, template))
			.join('\n\n');

		fs.writeFileSync(
			dest,
			`/* This file is generated by scripts/process-messages/index.js. Do not edit! */\n\n` +
				preamble +
				'\n\n' +
				output +
				'\n',
			'utf-8'
		);
	}

	transform('compile-errors', 'src/compiler/errors.js');
	transform('compile-warnings', 'src/compiler/warnings.js');

	transform('client-warnings', 'src/internal/client/warnings.js');
	transform('client-errors', 'src/internal/client/errors.js');
	transform('server-warnings', 'src/internal/server/warnings.js');
	transform('server-errors', 'src/internal/server/errors.js');
	transform('shared-errors', 'src/internal/shared/errors.js');
	transform('shared-warnings', 'src/internal/shared/warnings.js');
}

if (watch) {
	let running = false;
	let timeout;

	fs.watch('messages', { recursive: true }, (type, file) => {
		if (running) {
			timeout ??= setTimeout(() => {
				running = false;
				timeout = null;
			});
		} else {
			running = true;

			// eslint-disable-next-line no-console
			console.log('Regenerating messages...');
			run();
		}
	});
}

run();
